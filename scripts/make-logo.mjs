// Builds everything the app uses from the owner's three logo files
// (Kyphira_Logo-{Symbol,Horizontal,Stacked}_v1.svg, kept untouched in
// design/logo/):
//   src/components/kx/logoData.js        simplified symbol + both wordmarks, for the components
//   public/brand/kyphira-<form>.svg      the files as supplied (ink #141210)
//   public/brand/kyphira-<form>-reversed.svg   ink swapped for the dark edition's ink
//   public/brand/icon.svg, icon-dark.svg app icon and favicon tiles
//   public/icon.svg                      the manifest/favicon tile (paper)
//   index.html favicon                   a tiny inline version
// The symbol's smoke is drawn as dense polygons (~700 points each); the
// component version is simplified (Ramer–Douglas–Peucker) so it costs a few KB.
// Run: node scripts/make-logo.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const SRC = "design/logo";
const FORMS = { symbol: "Kyphira_Logo-Symbol_v1.svg", horizontal: "Kyphira_Logo-Horizontal_v1.svg", stacked: "Kyphira_Logo-Stacked_v1.svg" };
const INK = "#141210";
const DARK_INK = "#EDE6D8"; // PALETTES.dark.ink
const PAPER = "#F6F2EA";
const NIGHT = "#100E0A";

const read = (form) => readFileSync(`${SRC}/${FORMS[form]}`, "utf8");

function rdp(pts, eps) {
  if (pts.length < 3) return pts;
  const [ax, ay] = pts[0];
  const [bx, by] = pts[pts.length - 1];
  const dx = bx - ax, dy = by - ay;
  const len = Math.hypot(dx, dy) || 1;
  let idx = 0, max = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
    if (d > max) { max = d; idx = i; }
  }
  if (max <= eps) return [pts[0], pts[pts.length - 1]];
  return [...rdp(pts.slice(0, idx + 1), eps).slice(0, -1), ...rdp(pts.slice(idx), eps)];
}

// "M x y L x y … Z" polygon → simplified path string.
function simplify(d, eps) {
  const pts = [...d.matchAll(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g)].map((m) => [Number(m[1]), Number(m[2])]);
  const kept = rdp(pts, eps);
  const f = (n) => String(Math.round(n * 100) / 100);
  return `M${kept.map(([x, y]) => `${f(x)} ${f(y)}`).join("L")}Z`;
}
const round2 = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 100) / 100));

// The symbol's parts in drawing order, from the Symbol file's single group.
function symbolParts(svg, eps) {
  const inner = svg.match(/<g transform="[^"]*">([\s\S]*)<\/g>/)[1];
  const parts = [];
  for (const m of inner.matchAll(/<(path|rect)\b([^>]*)\/>/g)) {
    const attrs = Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
    if (m[1] === "rect") {
      const { x, y, width, height, rx } = attrs;
      const [X, Y, W, H, R] = [x, y, width, height, rx || 0].map(Number);
      parts.push({ d: `M${X + R} ${Y}H${X + W - R}Q${X + W} ${Y} ${X + W} ${Y + R}V${Y + H - R}Q${X + W} ${Y + H} ${X + W - R} ${Y + H}H${X + R}Q${X} ${Y + H} ${X} ${Y + H - R}V${Y + R}Q${X} ${Y} ${X + R} ${Y}Z`, fill: attrs.fill });
    } else {
      const polygon = attrs.d.includes("L") && !/[CcAaHhVvQq]/.test(attrs.d);
      parts.push({ d: polygon ? simplify(attrs.d, eps) : attrs.d, ...(attrs.fill && attrs.fill !== "none" ? { fill: attrs.fill } : { stroke: attrs.stroke, strokeWidth: Number(attrs["stroke-width"]) }) });
    }
  }
  return parts;
}

function wordmark(svg) {
  const m = svg.match(/<\/g><g transform="(translate\([^)]*\))"><path fill="#141210" d="([^"]+)"/);
  return { transform: m[1], d: round2(m[2]) };
}
function symbolTransform(svg) {
  return svg.match(/<g transform="([^"]*)">/)[1];
}
const viewBox = (svg) => svg.match(/viewBox="([^"]+)"/)[1];

const sym = read("symbol");
const horiz = read("horizontal");
const stack = read("stacked");

const parts = symbolParts(sym, 0.04);
const lockup = (svg) => ({ viewBox: viewBox(svg), symbol: symbolTransform(svg), word: wordmark(svg) });

const data = `// Generated by scripts/make-logo.mjs from design/logo/*.svg. Do not edit.
// SYMBOL: the mark's parts in drawing order, in the symbol's own coordinates
// (viewBox SYMBOL_BOX). fill "ink" follows the text colour; the other fills are the brand's brass.
export const SYMBOL_BOX = "70 16 148 330";
export const SYMBOL = ${JSON.stringify(parts.map((p) => (p.fill === INK ? { ...p, fill: "ink" } : p)))};
export const LOCKUPS = ${JSON.stringify({ horizontal: lockup(horiz), stacked: lockup(stack) })};
`;
writeFileSync("src/components/kx/logoData.js", data);

// Static files.
mkdirSync("public/brand", { recursive: true });
for (const form of Object.keys(FORMS)) {
  const svg = read(form);
  writeFileSync(`public/brand/kyphira-${form}.svg`, svg);
  writeFileSync(`public/brand/kyphira-${form}-reversed.svg`, svg.replaceAll(INK, DARK_INK));
}

// Tiles: the symbol centred on the page ground (64×64).
const tile = (bg, ink, eps) => {
  const body = symbolParts(sym, eps)
    .map((p) => (p.stroke ? `<path d="${p.d}" fill="none" stroke="${p.stroke}" stroke-width="${p.strokeWidth}" stroke-linecap="round"/>` : `<path d="${p.d}" fill="${p.fill === INK ? ink : p.fill}"/>`))
    .join("");
  // 148×330 box scaled to 48 px tall, centred in 64.
  const s = 48 / 330;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" fill="${bg}"/><g transform="translate(${(64 - 148 * s) / 2} 8) scale(${s}) translate(-70 -16)">${body}</g></svg>`;
};
writeFileSync("public/brand/icon.svg", tile(PAPER, INK, 0.04));
writeFileSync("public/brand/icon-dark.svg", tile(NIGHT, DARK_INK, 0.04));
writeFileSync("public/icon.svg", tile(PAPER, INK, 0.04));

// The favicon is inline in index.html (so /favicon.ico is never asked for); keep it small.
const fav = tile(PAPER, INK, 0.3).replaceAll('"', "'").replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E").replace(/ /g, "%20");
const html = readFileSync("index.html", "utf8").replace(/(<link rel="icon" href=")data:image\/svg\+xml,[^"]*(")/, `$1data:image/svg+xml,${fav}$2`);
writeFileSync("index.html", html);
console.log(`logo: ${parts.length} parts, favicon ${fav.length} chars`);
